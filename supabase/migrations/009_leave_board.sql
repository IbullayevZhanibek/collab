-- ============================================================
-- Выход участника из доски.
-- Существующие политики board_members разрешают удаление строк
-- только владельцу ("Owners can manage members"). Чтобы участник
-- мог сам покинуть доску, добавляем политику на удаление своей
-- собственной строки — но только для роли 'member' (владелец так
-- "покинуть" доску не может, для него это удаление доски целиком).
-- ============================================================

create policy "Members can leave board" on board_members
  for delete using (user_id = auth.uid() and role = 'member');
